/// ISO 4217 minor units for the currencies that do not use the default of 2
/// (ECMA-402 §16.5.1 CurrencyDigits). CLDR supplement `minorUnit`.
pub fn currency_digits(currency: &str) -> u32 {
    match currency {
        "BIF" | "CLP" | "DJF" | "GNF" | "ISK" | "JPY" | "KMF" | "KRW" | "PYG" | "RWF" | "UGX"
        | "VND" | "VUV" | "XAF" | "XOF" | "XPF" | "XAG" | "XAU" | "XBA" | "XBB" | "XBC" | "XBD"
        | "XDR" | "XPD" | "XPT" | "XSU" | "XUA" | "XXX" => 0,
        "BHD" | "IQD" | "JOD" | "KWD" | "LYD" | "OMR" | "TND" => 3,
        "CLF" | "UYW" => 4,
        _ => 2,
    }
}

