/// The generic record for the remaining base languages: en-US separators and
/// the en-US patterns.
const GENERIC: NumberLocaleData = NumberLocaleData {
    decimal: ".",
    group: ",",
    percent: "%",
    nan: "NaN",
    infinity: "∞",
    percent_pattern: "{number}{percentSign}",
    currency_patterns: EN_US_CURRENCY,
    units: EN_US_UNITS,
    primary_group: 3,
    secondary_group: 3,
    compact: EN_US_COMPACT,
    currencies: EN_US_CURRENCIES,
    range_separator: " – ",
    range_separator_collapsed: "–",
    approximately: "~",
};

/// Look up the locale data record: the exact tag, then the base language,
/// then the generic record (the plan's Cut 2 spike — hand-written data for
/// the pinned locales; the rest inherit the generic decimal surface).
pub fn locale_data(locale: &str) -> &'static NumberLocaleData {
    match locale {
        "en" | "en-US" | "en-GB" => &EN_US,
        "en-IN" => &EN_IN,
        "de" | "de-DE" | "de-AT" | "de-CH" => &DE_DE,
        "ja" | "ja-JP" => &JA_JP,
        "ko" | "ko-KR" => &KO_KR,
        "zh" | "zh-TW" | "zh-Hant-TW" => &ZH_TW,
        "zh-CN" | "zh-Hans-CN" => &ZH_CN,
        "pt" | "pt-PT" => &PT_PT,
        "pl" | "pl-PL" => &PT_PT,
        _ => &GENERIC,
    }
}
