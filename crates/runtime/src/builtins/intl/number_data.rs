/// A compact-notation entry: the exponent power and the display patterns
/// (with their affix strings). The pattern carries the separator literals
/// around `{number}` and `{compactSymbol}`/`{compactName}`; the affix is the
/// symbol/name string the placeholder resolves to. An empty affix means "no
/// affix" (the exponent collapses to 0 — the German short 10^3..10^5 gaps).
#[derive(Debug, Clone, Copy)]
pub struct CompactEntry {
    pub power: i32,
    pub short: &'static str,
    pub short_affix: &'static str,
    pub long: &'static str,
    pub long_affix: &'static str,
}

/// A unit entry: per display, the pattern (which carries the separator
/// literals around `{number}` and the `{unitPrefix}`/`{unitSuffix}`
/// placeholders) and the prefix/suffix strings the placeholders resolve to.
#[derive(Debug, Clone, Copy)]
pub struct UnitDisplay {
    pub pattern: &'static str,
    pub prefix: &'static str,
    pub suffix: &'static str,
    /// The plural (other-form) suffix, chosen when the formatted value is
    /// not 1/-1 (CLDR en unit patterns pluralize: "1 day" / "2 days";
    /// abbreviations like "hr" and compounds like "km/h" are invariant).
    pub plural_suffix: &'static str,
}

#[derive(Debug, Clone, Copy)]
pub struct UnitEntry {
    pub unit: &'static str,
    pub narrow: UnitDisplay,
    pub short: UnitDisplay,
    pub long: UnitDisplay,
}

/// The per-locale data record (ECMA-402 §16.2.3 LocaleData). The currency
/// and unit patterns are the raw sign-independent templates; the sign
/// variants are derived in `number_format.rs`.
#[derive(Debug, Clone, Copy)]
pub struct NumberLocaleData {
    pub decimal: &'static str,
    pub group: &'static str,
    pub percent: &'static str,
    pub nan: &'static str,
    pub infinity: &'static str,
    /// The percent style pattern (contains `{number}` and `{percentSign}`).
    pub percent_pattern: &'static str,
    /// Currency patterns, one per (display, sign-category) in the order
    /// [symbol/standard positive, negative, accounting-negative,
    /// code positive, code negative, name positive, name negative].
    pub currency_patterns: [&'static str; 7],
    pub units: &'static [UnitEntry],
    pub primary_group: u32,
    pub secondary_group: u32,
    pub compact: &'static [CompactEntry],
    pub currencies: &'static [(&'static str, &'static str, &'static str)],
    /// The unit/number separator the formatRange tests read dynamically.
    pub range_separator: &'static str,
    /// The separator when the range is collapsed (en-US: "–" vs " – ";
    /// pinned by formatRange/en-US.js and formatRangeToParts/en-US.js).
    pub range_separator_collapsed: &'static str,
    pub approximately: &'static str,
}

/// A unit entry constructor (the 13 arguments are the three display sets of
/// pattern/prefix/suffix plus the plural suffix; a data-table helper).
#[allow(clippy::too_many_arguments)]
const fn unit(
    unit: &'static str,
    narrow_pattern: &'static str,
    narrow_prefix: &'static str,
    narrow_suffix: &'static str,
    narrow_plural: &'static str,
    short_pattern: &'static str,
    short_prefix: &'static str,
    short_suffix: &'static str,
    short_plural: &'static str,
    long_pattern: &'static str,
    long_prefix: &'static str,
    long_suffix: &'static str,
    long_plural: &'static str,
) -> UnitEntry {
    UnitEntry {
        unit,
        narrow: UnitDisplay {
            pattern: narrow_pattern,
            prefix: narrow_prefix,
            suffix: narrow_suffix,
            plural_suffix: narrow_plural,
        },
        short: UnitDisplay {
            pattern: short_pattern,
            prefix: short_prefix,
            suffix: short_suffix,
            plural_suffix: short_plural,
        },
        long: UnitDisplay {
            pattern: long_pattern,
            prefix: long_prefix,
            suffix: long_suffix,
            plural_suffix: long_plural,
        },
    }
}

const fn compact(
    power: i32,
    short: &'static str,
    short_affix: &'static str,
    long: &'static str,
    long_affix: &'static str,
) -> CompactEntry {
    CompactEntry {
        power,
        short,
        short_affix,
        long,
        long_affix,
    }
}

