//! Generates the case-folding preimage tables used by the search prefilter.
//!
//! `fold_class` needs, for a canonical form, every code point that folds to
//! it. Only code points whose canonical form differs from themselves can be
//! members, so the table is built here on the host — one enumeration of the
//! code point space per mode — instead of at run time. The old runtime scan
//! walked all 1,114,112 code points to find a few thousand entries, which
//! made the first folded compile pathological under an interpreted build.

use std::fmt::Write as _;

fn main() {
    // The mappings come from this crate; a change there must regenerate the
    // table (a stale table would let the prefilter skip a real match).
    println!("cargo:rerun-if-changed=../unicode/src/lib.rs");

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs; do not edit.\n");
    generated.push_str("type FoldTable = &'static [(u32, &'static [(u32, u32)])];\n");
    write_table(
        &mut generated,
        "FOLD_CLASSES_UNICODE",
        unicode::simple_case_fold,
    );
    write_table(
        &mut generated,
        "FOLD_CLASSES_LEGACY",
        unicode::non_unicode_canonicalize,
    );

    let path = std::path::Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR is set"))
        .join("fold_classes.rs");
    std::fs::write(&path, generated).expect("write fold_classes.rs");
}

fn write_table(out: &mut String, name: &str, canonicalize: fn(u32) -> u32) {
    let mut preimage: std::collections::HashMap<u32, Vec<u32>> = std::collections::HashMap::new();
    for cp in 0u32..=0x10FFFF {
        let canonical = canonicalize(cp);
        if canonical != cp {
            preimage.entry(canonical).or_default().push(cp);
        }
    }
    let mut entries: Vec<(u32, Vec<(u32, u32)>)> = preimage
        .into_iter()
        .map(|(canonical, mut members)| {
            members.push(canonical);
            (canonical, ranges_of(&members))
        })
        .collect();
    entries.sort_unstable_by_key(|&(canonical, _)| canonical);

    writeln!(out, "static {name}: FoldTable = &[").expect("write table header");
    for (canonical, ranges) in entries {
        write!(out, "    (0x{canonical:X}, &[").expect("write entry");
        for (start, end) in ranges {
            write!(out, "(0x{start:X}, 0x{end:X}),").expect("write range");
        }
        out.push_str("]),\n");
    }
    out.push_str("];\n");
}

/// The engine's `ranges_of`; duplicated because a build script cannot depend
/// on the crate it builds.
fn ranges_of(members: &[u32]) -> Vec<(u32, u32)> {
    let mut sorted = members.to_vec();
    sorted.sort_unstable();
    sorted.dedup();
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for cp in sorted {
        match ranges.last_mut() {
            Some((_, end)) if cp == *end + 1 => *end = cp,
            _ => ranges.push((cp, cp)),
        }
    }
    ranges
}
